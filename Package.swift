// swift-tools-version: 6.0
//
// MacroSIP - SwiftPM manifest.
// PJSIP and its dependencies (OpenSSL 3, Opus) are prebuilt by scripts/build-pjsip.sh as universal
// (arm64 + x86_64) static archives into third_party/pjsip/{include,lib} and third_party/deps/universal/lib,
// so both a native `swift build` and `swift build --arch arm64 --arch x86_64` link against them.
// Swift reaches PJSIP only through the CPJSUA C target.

import PackageDescription

// Absolute paths: unsafe -I/-L flags are not resolved relative to the package by every tool.
let pjsipRoot = Context.packageDirectory + "/third_party/pjsip"
let pjsipInclude = pjsipRoot + "/include"
let pjsipLib = pjsipRoot + "/lib"
let depsLib = Context.packageDirectory + "/third_party/deps/universal/lib"

// Keep in sync with third_party/pjsip/LINKFLAGS (generated by build-pjsip.sh).
let pjsipLibraries = [
    "pjsua", "pjsip-ua", "pjsip-simple", "pjsip",
    "pjmedia-codec", "pjmedia-videodev", "pjmedia-audiodev", "pjmedia",
    "pjnath", "pjlib-util", "srtp", "resample",
    "gsmcodec", "speex", "ilbccodec", "g7221codec",     // GSM, Speex, iLBC, G.722.1 (26.2)
    "webrtc", "pj",
]

let pjsipLinkerSettings: [LinkerSetting] = [
    .unsafeFlags(
        ["-L\(pjsipLib)"] + pjsipLibraries.map { "-l\($0)" } + [
            // Static archives built from pinned sources by build-pjsip.sh (no dylib dependencies: the
            // app must run on machines without Homebrew).
            depsLib + "/libopus.a",
            depsLib + "/libssl.a",
            depsLib + "/libcrypto.a",
        ]
    ),
    .linkedLibrary("c++"),          // libwebrtc contains C++ objects
    .linkedLibrary("m"),
    .linkedLibrary("pthread"),
    .linkedFramework("CoreAudio"),
    .linkedFramework("CoreServices"),
    .linkedFramework("AudioUnit"),
    .linkedFramework("AudioToolbox"),
    .linkedFramework("Foundation"),
    .linkedFramework("AppKit"),
]

// Swift modules importing CPJSUA need the PJSIP headers on the Clang importer path.
let pjsipSwiftSettings: [SwiftSetting] = [
    .unsafeFlags(["-Xcc", "-I\(pjsipInclude)"]),
]

// Sparkle 2 (in-app updates, ADR 0013) ships as a prebuilt XCFramework (arm64 + x86_64). The app
// loads it from Contents/Frameworks, where scripts/make-app.sh copies it.
let appLinkerSettings: [LinkerSetting] = [
    .unsafeFlags(["-Xlinker", "-rpath", "-Xlinker", "@executable_path/../Frameworks"]),
]

let package = Package(
    name: "MacroSIP",
    defaultLocalization: "en",
    platforms: [.macOS(.v14)],
    products: [
        .executable(name: "MacroSIPApp", targets: ["MacroSIPApp"]),
        .executable(name: "pjsip-smoke", targets: ["pjsip-smoke"]),
        .executable(name: "macrosip-cli", targets: ["macrosip-cli"]),
    ],
    dependencies: [
        .package(url: "https://github.com/sparkle-project/Sparkle", exact: "2.7.3"),
    ],
    targets: [
        .target(
            name: "CPJSUA",
            path: "Sources/CPJSUA",
            cSettings: [
                .define("PJ_AUTOCONF", to: "1"),
                .unsafeFlags(["-I\(pjsipInclude)"]),
            ],
            linkerSettings: pjsipLinkerSettings
        ),
        // System OpenLDAP client (libldap in the macOS SDK) for LDAP directory sources (docs/DIRECTORY.md).
        .target(
            name: "CLDAP",
            path: "Sources/CLDAP",
            linkerSettings: [.linkedLibrary("ldap")]
        ),
        .executableTarget(
            name: "pjsip-smoke",
            dependencies: ["CPJSUA"],
            path: "Sources/pjsip-smoke",
            swiftSettings: pjsipSwiftSettings
        ),
        .target(
            name: "MacroSIPCore",
            dependencies: ["CPJSUA", "CLDAP"],
            path: "Sources/MacroSIPCore",
            swiftSettings: pjsipSwiftSettings
        ),
        .executableTarget(
            name: "macrosip-cli",
            dependencies: ["MacroSIPCore"],
            path: "Sources/macrosip-cli",
            swiftSettings: pjsipSwiftSettings
        ),
        .executableTarget(
            name: "MacroSIPApp",
            dependencies: [
                "MacroSIPCore",
                .product(name: "Sparkle", package: "Sparkle"),
            ],
            path: "Sources/MacroSIPApp",
            resources: [.process("Resources")],     // en.lproj / ru.lproj Localizable.strings and .stringsdict
            swiftSettings: pjsipSwiftSettings,
            linkerSettings: appLinkerSettings
        ),
        .testTarget(
            name: "MacroSIPCoreTests",
            dependencies: ["MacroSIPCore"],
            path: "Tests/MacroSIPCoreTests",
            swiftSettings: pjsipSwiftSettings
        ),
    ]
)
